<#
.SYNOPSIS
  Creates a <Name>.shadow.csproj next to every SubActions/**/<Name>.cs that lacks one and adds it to
  csharp.sln under a solution folder mirroring the directory path.

.EXAMPLE
  .\add-shadow-projects.ps1
  .\add-shadow-projects.ps1 -WhatIf
#>
[CmdletBinding(SupportsShouldProcess)]
param()

$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$sln = Join-Path $root 'csharp.sln'
$subActions = Join-Path $root 'SubActions'

# Directory names skipped when scanning for .cs files. Matched as whole path segments.
$builtinExcludedDirs = 'obj', 'bin'
$userExcludedDirs = 'wip'
$excludedDirsPattern = '[\\/](' +
(($builtinExcludedDirs + $userExcludedDirs | ForEach-Object { [regex]::Escape($_) }) -join '|') +
')[\\/]'

$usingMap = @(
  @{ Pattern = '^BroStreamerTools(\.|$)'; Prop = 'SbotRefBroStreamerTools'; Value = 'true' }
  @{ Pattern = '^Newtonsoft\.Json(\.|$)'; Prop = 'SbotRefNewtonsoftJson'; Value = 'true' }
)

$propOrder = 'SbotRefFramework', 'SbotRefBroStreamerTools', 'SbotRefNewtonsoftJson'

$indent = '  '
$groupIndent = $indent
$propIndent = $indent * 2

$beginText = '<!-- sbotref:begin'
$beginMarker = "$beginText (generated by add-shadow-projects.ps1 from using`n" +
"${propIndent}directives; add manual props outside this block) -->"
$endMarker = '<!-- sbotref:end -->'

function Get-GeneratedBlock([string]$csPath) {
  $props = @{}

  foreach ($line in Get-Content $csPath) {
    if ($line -notmatch '^\s*using\s+([A-Za-z_][\w.]*)\s*;') {
      continue
    }
    $namespace = $Matches[1]
    foreach ($m in $usingMap) {
      if ($namespace -match $m.Pattern) {
        $props[$m.Prop] = $m.Value
      }
    }
  }

  $lines = @($beginMarker)
  foreach ($k in $propOrder) {
    if ($props.ContainsKey($k)) {
      $lines += "$propIndent<$k>$($props[$k])</$k>"
    }
  }
  $lines += "$propIndent$endMarker"
  return $lines -join "`n"
}

function New-Csproj([string]$block) {
  return @(
    '<Project Sdk="Microsoft.NET.Sdk">'
    "$groupIndent<PropertyGroup>"
    "$propIndent$block"
    "$groupIndent</PropertyGroup>"
    '</Project>'
    ''
  ) -join "`n"
}

function Merge-Csproj([string]$text, [string]$block) {
  $markers = `
    [regex]('(?s)' + [regex]::Escape($beginText) + '.*?' + [regex]::Escape($endMarker))
  $m = $markers.Match($text)
  if ($m.Success) {
    return $text.Substring(0, $m.Index) + $block + $text.Substring($m.Index + $m.Length)
  }

  $text = $text -replace '(?m)^[ \t]*<SbotRef\w+>[^<]*</SbotRef\w+>[ \t]*\n', ''

  $tag = '<PropertyGroup>'
  $i = $text.IndexOf($tag)
  if ($i -ge 0) {
    $at = $i + $tag.Length
    return $text.Substring(0, $at) + "`n$propIndent$block" + $text.Substring($at)
  }

  $open = [regex]::Match($text, '<Project[^>]*[^/]>[ \t]*\n')
  if ($open.Success) {
    $at = $open.Index + $open.Length
    return $text.Substring(0, $at) `
      + "$groupIndent<PropertyGroup>`n$propIndent$block`n$groupIndent</PropertyGroup>`n" `
      + $text.Substring($at)
  }
  return New-Csproj $block
}

$existing = @(dotnet sln $sln list | Select-Object -Skip 2 | ForEach-Object { $_.Trim() })

$csFiles = Get-ChildItem $subActions -Recurse -Filter *.cs |
  Where-Object { $_.FullName -notmatch $excludedDirsPattern }

$created = 0
$updated = 0
$added = 0
foreach ($cs in $csFiles) {
  $csproj = Join-Path $cs.DirectoryName ($cs.BaseName + '.shadow.csproj')
  $relCsproj = [IO.Path]::GetRelativePath($root, $csproj)

  $block = Get-GeneratedBlock $cs.FullName
  if (-not (Test-Path $csproj)) {
    $content = New-Csproj $block
    if ($PSCmdlet.ShouldProcess($relCsproj, 'create')) {
      Set-Content -Path $csproj -Value ($content -replace "`n", "`r`n") -NoNewline `
        -Encoding utf8NoBOM
      Write-Host "created  $relCsproj"
      $created++
    }
    $content = $null
    $current = $null
  } else {
    $current = (Get-Content $csproj -Raw) -replace "\r?\n", "`n"
    $content = Merge-Csproj $current $block
  }

  if ($content -and $content -ne $current) {
    if ($PSCmdlet.ShouldProcess($relCsproj, 'update SbotRef props')) {
      Set-Content -Path $csproj -Value ($content -replace "`n", "`r`n") -NoNewline `
        -Encoding utf8NoBOM
      Write-Host "updated  $relCsproj"
      $updated++
    }
  }

  if ($existing -notcontains $relCsproj) {
    $folder = ([IO.Path]::GetRelativePath($root, $cs.DirectoryName)) -replace '\\', '/'
    if ($PSCmdlet.ShouldProcess($relCsproj, "add to sln under $folder")) {
      dotnet sln $sln add $csproj --solution-folder $folder | Out-Null
      Write-Host "sln add  $relCsproj  ->  $folder"
      $added++
    }
  }
}

Write-Host "done: $created csproj created, $updated updated, $added added to sln"
