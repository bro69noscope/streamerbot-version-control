<#
.SYNOPSIS
  Generates ObsMappings.g.cs: every {{TOKEN}} => value of the OBS mappings file, baked into the DLL.
  Uses the same override rule as the OBS templater (dotsource-obs-paths.ps1): any
  obs-vcs-mappings*.json5 that is not the .bro one replaces the .bro one.
#>
param([Parameter(Mandatory=$true)] [string]$OutFile)

$ErrorActionPreference = 'Stop'

$repo = $env:STREAMING_REPO_PATH
if (-not $repo) {
  throw 'STREAMING_REPO_PATH is not set, cannot resolve the OBS mappings file'
}

. (Join-Path $repo 'external\obs\version-control\dotsource-obs-paths.ps1')

# Same flattening as Read-MappingsFile (category => token => value), minus the vcs-helpers module,
# which refuses to load outside the templaters (needs RepoPath and prettier).
$json5 = (Join-Path $repo 'node_modules\json5') -replace '\\', '/'
$file = $script:ObsMappingsPath -replace '\\', '/'
$raw = node -e "
  const JSON5 = require('$json5');
  console.log(JSON.stringify(JSON5.parse(require('fs').readFileSync('$file','utf8'))));
" | ConvertFrom-Json -AsHashtable

$rules = foreach ($category in $raw.Keys) {
  foreach ($token in $raw[$category].Keys) {
    [PSCustomObject]@{ Token = $token; Value = [string]$raw[$category][$token] }
  }
}

$entries = foreach ($rule in $rules | Sort-Object Token) {
  $value = $rule.Value -replace '"', '""'
  "        [@`"$($rule.Token -replace '"', '""')`"] = @`"$value`","
}

$source = @(
  '// <auto-generated> by gen-obs-mappings.ps1, do not edit. Not committed.'
  "// source: $script:ObsMappingsPath"
  'using System.Collections.Generic;'
  ''
  'namespace BroStreamerTools;'
  ''
  'static class ObsMappingValues'
  '{'
  '    public static readonly Dictionary<string, string> All = new Dictionary<string, string>'
  '    {'
  $entries
  '    };'
  '}'
  ''
) -join "`n"

$dir = Split-Path $OutFile
if (-not (Test-Path $dir)) {
  New-Item -ItemType Directory -Path $dir | Out-Null
}

# Only touch the file when it changed, so an unchanged mapping does not force a recompile.
if (-not (Test-Path $OutFile) -or [IO.File]::ReadAllText($OutFile) -ne $source) {
  [IO.File]::WriteAllText($OutFile, $source, [Text.UTF8Encoding]::new($false))
  Write-Host "generated $OutFile from $script:ObsMappingsPath"
}
